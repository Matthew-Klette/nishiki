/**
 * Fontsource ships Zen Kaku Gothic New as ~120 unicode-range slices per weight, which makes the
 * stylesheet ~300 kB. This keeps only the slices that cover Japanese characters used in src/,
 * and writes src/fonts/zen-kaku.css. Re-run (npm run fonts) after adding new kanji or kana.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "node_modules/@fontsource/zen-kaku-gothic-new");
const outDir = join(root, "src/fonts");
const WEIGHTS = [500, 700];
const JAPANESE = /[\u3000-\u30ff\u3400-\u9fff\uff00-\uffef]/gu;

function sourceFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (path.startsWith(outDir)) return [];
    if (statSync(path).isDirectory()) return sourceFiles(path);
    return /\.(tsx?|css|html)$/.test(name) ? [path] : [];
  });
}

const used = new Set(
  [...sourceFiles(join(root, "src")), join(root, "index.html")].flatMap((f) => readFileSync(f, "utf8").match(JAPANESE) ?? []),
);
const codepoints = [...used].map((c) => c.codePointAt(0));

function covers(range) {
  return range.split(",").some((part) => {
    const [lo, hi] = part.trim().replace(/^U\+/i, "").split("-").map((h) => parseInt(h, 16));
    return codepoints.some((cp) => cp >= lo && cp <= (hi ?? lo));
  });
}

const blocks = WEIGHTS.flatMap((weight) => {
  const css = readFileSync(join(pkg, `${weight}.css`), "utf8");
  return [...css.matchAll(/@font-face\s*{[^}]*}/g)].map((m) => m[0]).filter((block) => {
    const range = block.match(/unicode-range:\s*([^;]+);/);
    return range && covers(range[1]);
  });
});

if (blocks.length === 0) throw new Error("No Zen Kaku slices matched; is the package installed?");

const filesDir = relative(outDir, join(pkg, "files")).split("\\").join("/");
const out = [
  "/* Generated by scripts/subset-jp-fonts.mjs. Do not edit by hand. */",
  `/* ${used.size} characters: ${[...used].sort().join("")} */`,
  ...blocks.map((b) => b.replaceAll("./files", filesDir)),
].join("\n\n");

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "zen-kaku.css"), out + "\n");
console.log(`zen-kaku.css: ${blocks.length} slices for ${used.size} characters`);
